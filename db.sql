CREATE TABLE public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  oidc_token text NOT NULL,
  email text NOT NULL,
  system_roles varchar(32)[] NOT NULL DEFAULT ARRAY[]::varchar(32)[], -- admin
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.user_theme_collections (
  user_id bigint NOT NULL REFERENCES public.users(id),
  theme_collection_id bigint NOT NULL REFERENCES public.theme_collections(id),
  role varchar(32) NOT NULL -- owner, editor, viewer
  PRIMARY KEY (user_id, theme_collection_id )
);

CREATE TABLE public.theme_collections (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  is_public boolean NOT NULL DEFAULT false,
  parameters jsonb  NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(preferences) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.theme_collection_themes (
  theme_collection_id bigint NOT NULL REFERENCES public.theme_collections(id),
  theme_id bigint NOT NULL REFERENCES public.themes(id),
  PRIMARY KEY (theme_collection_id, theme_id)
);

CREATE TABLE public.themes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  is_public boolean NOT NULL DEFAULT false,
  parameters jsonb  NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(preferences) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.styles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  theme_id bigint NOT NULL REFERENCES public.themes(id),
  type varchar(32) NOT NULL, -- transform, render
  data jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(preferences) = 'object'),
);

CREATE TABLE public.media(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES public.processing_request (id),
  mime_type text NOT NULL,
  storage_path text NOT NULL,
  public_path text NOT NULL
);

CREATE TABLE public.processing_request (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type varchar(32) NOT NULL, -- templating, rendering
  user_id bigint NOT NULL REFERENCES public.users(id),
  theme_id bigint NOT NULL REFERENCES public.themes(id),
  parameters jsonb  NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(preferences) = 'object')
);
CREATE TABLE public.processing_result (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES public.processing_request (id),
  storage_path text NOT NULL,
  download_code varchar(64) NOT NULL
);


CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
RETURN NEW;
END;
$$;
CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON public.users FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER themes_set_updated_at BEFORE UPDATE ON public.themes FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER theme_collections_set_updated_at BEFORE UPDATE ON public.theme_collections FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();