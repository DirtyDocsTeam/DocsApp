ALTER TABLE public.themes
    ADD COLUMN owner_user_id bigint REFERENCES public.users(id),
    ADD COLUMN deleted_at timestamptz;

ALTER TABLE public.job_request
    ALTER COLUMN processing_media_id DROP NOT NULL,
    ADD COLUMN deleted_at timestamptz,
    ADD COLUMN idempotency_key varchar(128),
    ADD COLUMN request_fingerprint varchar(64),
    ADD COLUMN delivery_key varchar(128),
    ADD COLUMN delivery_attempts integer NOT NULL DEFAULT 0;

ALTER TABLE public.media
    ADD COLUMN deletion_failed_at timestamptz,
    ADD COLUMN deletion_attempts integer NOT NULL DEFAULT 0,
    ADD COLUMN eviction_started_at timestamptz,
    ADD COLUMN evicted_at timestamptz;

CREATE TABLE public.job_expected_media (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES public.job_request(id),
    user_id bigint NOT NULL REFERENCES public.users(id),
    file_hash varchar(128) NOT NULL,
    role varchar(32) NOT NULL,
    state varchar(32) NOT NULL DEFAULT 'expected',
    media_id bigint REFERENCES public.media(id),
    expires_at timestamptz NOT NULL,
    receipt_key varchar(128),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (request_id, file_hash, role)
);

CREATE TRIGGER job_expected_media_set_updated_at
    BEFORE UPDATE ON public.job_expected_media
    FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE public.domain_event_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type varchar(64) NOT NULL,
    aggregate_id bigint NOT NULL,
    owner_user_id bigint REFERENCES public.users(id),
    event_type varchar(64) NOT NULL,
    schema_version integer NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    delivered_at timestamptz
);

CREATE UNIQUE INDEX job_request_user_id_idempotency_key_uidx
    ON public.job_request (user_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;
CREATE INDEX job_expected_media_receipt_idx
    ON public.job_expected_media (user_id, file_hash, state);
CREATE INDEX job_expected_media_expiry_idx
    ON public.job_expected_media (expires_at)
    WHERE state = 'expected';
CREATE INDEX media_cleanup_idx
    ON public.media (delete_at)
    WHERE delete_at IS NOT NULL;
CREATE INDEX domain_event_outbox_pending_idx
    ON public.domain_event_outbox (id)
    WHERE delivered_at IS NULL;
